using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;
using ShowingBooking.Application.Abstractions;
using ShowingBooking.Domain;

namespace ShowingBooking.Infrastructure;

public sealed class ShowingDbContext(DbContextOptions<ShowingDbContext> options) : DbContext(options)
{
    public DbSet<Slot> Slots => Set<Slot>();
    public DbSet<Booking> Bookings => Set<Booking>();
    public DbSet<BookingHistoryEntry> History => Set<BookingHistoryEntry>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // SQLite cannot sort or compare DateTimeOffset values. Storing the UTC ticks as a number
        // keeps ORDER BY and range filters correct. Everything in this API is UTC anyway.
        var utcTicks = new ValueConverter<DateTimeOffset, long>(
            value => value.UtcTicks,
            ticks => new DateTimeOffset(ticks, TimeSpan.Zero));

        modelBuilder.Entity<Slot>(slot =>
        {
            slot.HasKey(s => s.Id);
            // Ids are created in the domain. Telling EF it never generates them makes it treat
            // new entities found through navigations as INSERTs, not UPDATEs.
            slot.Property(s => s.Id).ValueGeneratedNever();
            slot.Property(s => s.PropertyId).IsRequired().HasMaxLength(100);
            slot.Property(s => s.StartsAt).HasConversion(utcTicks);

            // The optimistic concurrency token: UPDATE ... WHERE Id = @id AND Version = @loadedVersion.
            // If 0 rows are updated, another request changed the slot first.
            slot.Property(s => s.Version).IsConcurrencyToken();

            slot.Ignore(s => s.SeatsRemaining);
            slot.HasIndex(s => new { s.PropertyId, s.StartsAt });

            slot.HasMany(s => s.Bookings)
                .WithOne(b => b.Slot)
                .HasForeignKey(b => b.SlotId);
            slot.Navigation(s => s.Bookings).UsePropertyAccessMode(PropertyAccessMode.Field);
        });

        modelBuilder.Entity<Booking>(booking =>
        {
            booking.HasKey(b => b.Id);
            booking.Property(b => b.Id).ValueGeneratedNever();
            booking.Property(b => b.RenterEmail).IsRequired().HasMaxLength(254);
            booking.Property(b => b.Status).HasConversion<string>().HasMaxLength(20);
            booking.Property(b => b.CreatedAt).HasConversion(utcTicks);
            booking.Property(b => b.Version).IsConcurrencyToken();

            // Safety net behind the domain rule: even if two requests slipped past the version
            // check, the database refuses a second Confirmed booking for the same renter and slot.
            booking.HasIndex(b => new { b.SlotId, b.RenterEmail })
                .IsUnique()
                .HasFilter("\"Status\" = 'Confirmed'");

            booking.HasMany(b => b.History)
                .WithOne()
                .HasForeignKey(h => h.BookingId);
            booking.Navigation(b => b.History).UsePropertyAccessMode(PropertyAccessMode.Field);
        });

        modelBuilder.Entity<BookingHistoryEntry>(entry =>
        {
            entry.HasKey(h => h.Id); // long, generated by the database, increasing
            entry.Property(h => h.FromStatus).HasConversion<string>().HasMaxLength(20);
            entry.Property(h => h.ToStatus).HasConversion<string>().HasMaxLength(20);
            entry.Property(h => h.Actor).HasConversion<string>().HasMaxLength(20);
            entry.Property(h => h.Reason).HasMaxLength(500);
            entry.Property(h => h.OccurredAt).HasConversion(utcTicks);
            entry.HasIndex(h => h.BookingId);
        });
    }

    /// <summary>
    /// Turns "I lost a race" database failures into one exception the application layer understands.
    /// </summary>
    public override async Task<int> SaveChangesAsync(
        bool acceptAllChangesOnSuccess, CancellationToken cancellationToken = default)
    {
        try
        {
            return await base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
        }
        catch (DbUpdateConcurrencyException ex)
        {
            throw new ConcurrencyConflictException("The row was changed by another request.", ex);
        }
        catch (DbUpdateException ex) when (IsContention(ex))
        {
            throw new ConcurrencyConflictException("The database rejected the write because of contention.", ex);
        }
    }

    private static bool IsContention(DbUpdateException ex) => ex.InnerException is SqliteException
    {
        SqliteErrorCode: 5 or 6 // SQLITE_BUSY, SQLITE_LOCKED: another writer holds the database
    } or SqliteException
    {
        SqliteErrorCode: 19, SqliteExtendedErrorCode: 2067 // UNIQUE constraint (duplicate Confirmed booking)
    };
}
